// Package danmaku 是弹幕渲染方案的 spike：把 []Item 时间轴弹幕编译成 ASS
// 字幕文本（mpv 原生支持 --sub-file=ASS，含 \move 滚动与颜色）。纯 Go、
// 无平台依赖，Linux go test 直接跑。
//
// 输出为 ASS 的三个标准段：[Script Info] / [V4+ Styles] / [Events]
//（任务里的 Scenes/Past/Events 即指这三段头）。
//
// 同屏防碰撞 = 简单分轨：全部事件共用一条 Style，轨道号写进 MarginV；
// 新事件找"上一条已滚出碰撞区"的最早轨道，没有则开新轨。
// 速度模型统一 v = PlayResX/ScrollDurMs px/ms，追尾判定
// free(t) >= prev.t + (prevW + GapPx)/v ——只算水平入轨间隔，
// 不做字宽精确遮挡，够 spike 验证"纯 Go 可产 ASS"这条链路。
package danmaku

import (
	"fmt"
	"strconv"
	"strings"
	"unicode/utf8"
)

// Item 一条弹幕。TimeMs=出现时刻（相对视频时间轴），Color="#RRGGBB" 或空=白，
// Size=字号(px, <=0 用 DefaultSize)。
type Item struct {
	TimeMs int64
	Text   string
	Color  string
	Size   int
}

const (
	PlayResX      = 1280
	PlayResY      = 720
	DefaultSize   = 38          // 字号 px
	LineHeight    = 52          // 轨距 px
	ScrollDurMs   = int64(4000) // 右边缘→完全出左边缘
	CharWidthRune = 0.55        // 每 rune 宽 ≈ size*该系数（CJK≈1.0 半宽单位，粗略）
	GapPx         = 20          // 同轨前后弹幕最小间距
)

// assTime 毫秒 → ASS 时间 "H:MM:SS.cc"（cc=厘秒）。
func assTime(ms int64) string {
	cs := ms / 10
	h := cs / 360000
	cs -= h * 360000
	m := cs / 6000
	cs -= m * 6000
	s := cs / 100
	cs -= s * 100
	return fmt.Sprintf("%d:%02d:%02d.%02d", h, m, s, cs)
}

// assColor "#RRGGBB" → ASS "&HBBGGRR&"；空/非法 → 白。
func assColor(c string) string {
	c = strings.TrimSpace(c)
	if len(c) != 7 || c[0] != '#' {
		return `&HFFFFFF&`
	}
	for _, r := range c[1:] {
		if !(r >= '0' && r <= '9' || r >= 'a' && r <= 'f' || r >= 'A' && r <= 'F') {
			return `&HFFFFFF&`
		}
	}
	rr, _ := strconv.ParseUint(c[1:3], 16, 8)
	gg, _ := strconv.ParseUint(c[3:5], 16, 8)
	bb, _ := strconv.ParseUint(c[5:7], 16, 8)
	return fmt.Sprintf("&H%02X%02X%02X&", bb, gg, rr)
}

// textWidthPx 粗估滚动宽：rune 数 × size × 系数。
func textWidthPx(text string, size int) int {
	if size <= 0 {
		size = DefaultSize
	}
	n := utf8.RuneCountInString(text)
	return int(float64(n) * float64(size) * CharWidthRune)
}

type laneState struct {
	lastTimeMs int64
	lastWidth  int
	lastSize   int
}

// Render 生成完整 ASS 文本。输入不必已排序（内部按 TimeMs 稳定排序）。
func Render(items []Item) string {
	type ev struct {
		Item
		lane int
	}
	sorted := make([]Item, len(items))
	copy(sorted, items)
	// 插入排序即可（spike 数据量小；v2 再换 slices.SortStableFunc）
	for i := 1; i < len(sorted); i++ {
		for j := i; j > 0 && sorted[j].TimeMs < sorted[j-1].TimeMs; j-- {
			sorted[j], sorted[j-1] = sorted[j-1], sorted[j]
		}
	}
	vPerMs := float64(PlayResX) / float64(ScrollDurMs)
	var lanes []laneState
	evs := make([]ev, 0, len(sorted))
	for _, it := range sorted {
		size := it.Size
		if size <= 0 {
			size = DefaultSize
		}
		w := textWidthPx(it.Text, size)
		placed := -1
		for li, ln := range lanes {
			freeAt := ln.lastTimeMs + int64(float64(ln.lastWidth+GapPx)/vPerMs)
			if it.TimeMs >= freeAt {
				placed = li
				break
			}
		}
		if placed == -1 { // 全占用 → 开新轨；轨满 PlayResY 则并入轨 0（v2 再改滚速）
			placed = len(lanes)
			if placed*LineHeight >= PlayResY {
				placed = 0
			}
			if placed == len(lanes) {
				lanes = append(lanes, laneState{})
			}
		}
		lanes[placed] = laneState{lastTimeMs: it.TimeMs, lastWidth: w, lastSize: size}
		evs = append(evs, ev{Item: it, lane: placed})
	}

	var b strings.Builder
	b.WriteString("[Script Info]\n")
	b.WriteString("; generated by zgj spike danmaku\n")
	b.WriteString("ScriptType: v4.00+\n")
	b.WriteString(fmt.Sprintf("PlayResX: %d\nPlayResY: %d\nWrapStyle: 2\nScaledBorderAndShadow: yes\n\n", PlayResX, PlayResY))
	b.WriteString("[V4+ Styles]\n")
	b.WriteString("Format: Name, Fontname, Fontsize, PrimaryColour, SecondaryColour, OutlineColour, BackColour, Bold, Italic, Underline, StrikeOut, ScaleX, ScaleY, Spacing, Angle, BorderStyle, Outline, Shadow, Alignment, MarginL, MarginR, MarginV, Encoding\n")
	b.WriteString(fmt.Sprintf("Style: Default,Microsoft YaHei,%d,&HFFFFFF&,&HFFFFFF&,&H000000&,&H80000000&,0,0,0,0,100,100,0,0,1,2,1,7,10,10,0,1\n\n", DefaultSize))
	b.WriteString("[Events]\n")
	b.WriteString("Format: Layer, Start, End, Style, Name, MarginL, MarginR, MarginV, Effect, Text\n")
	for _, e := range evs {
		y := e.lane*LineHeight + LineHeight/2
		w := textWidthPx(e.Text, func() int {
			if e.Size > 0 {
				return e.Size
			}
			return DefaultSize
		}())
		end := e.TimeMs + ScrollDurMs
		move := fmt.Sprintf(`{\move(%d,%d,%d,%d)\c%s\fs%d}`, PlayResX, y, -w, y, assColor(e.Color), func() int {
			if e.Size > 0 {
				return e.Size
			}
			return DefaultSize
		}())
		b.WriteString(fmt.Sprintf("Dialogue: 0,%s,%s,Default,,0,0,%d,,%s%s\n",
			assTime(e.TimeMs), assTime(end), y, move, escapeAss(e.Text)))
	}
	return b.String()
}

func escapeAss(s string) string {
	s = strings.ReplaceAll(s, "\\", "\\\\")
	s = strings.ReplaceAll(s, "{", "(")
	s = strings.ReplaceAll(s, "}", ")")
	s = strings.ReplaceAll(s, "\n", "\\N")
	return s
}
