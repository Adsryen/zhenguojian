const dicts: Record<Locale, Record<string, string>> = { zh, en }

/** 翻译；缺 key 回退 zh 表，再回退 key 本身。模板里调用即随 locale 响应。 */
export function t(key: string): string {
  const table = dicts[locale.value]
  return table[key] ?? zh[key] ?? key
}

/**
 * 带参翻译（函数式键）：字典值内用 {name} 占位，params 逐一替换；未命中的占位符原样保留。
 * 模板/computed 里调用同样随 locale 响应（内部读 locale.value）。
 */
export function tf(key: string, params: Record<string, string | number>): string {
  const table = dicts[locale.value]
  const tpl = table[key] ?? zh[key] ?? key
  return tpl.replace(/\{(\w+)\}/g, (raw, name: string) => (name in params ? String(params[name]) : raw))
}

